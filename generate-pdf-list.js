#!/usr/bin/env node

/**
 * Script to automatically detect PDFs in the pdfs/ directory
 * and generate a manifest file for the web application
 */

const fs = require('fs');
const path = require('path');

const PDFS_DIR = path.join(__dirname, 'pdfs');
const OUTPUT_FILE = path.join(__dirname, 'pdf-manifest.json');

// Helper function to create a guide ID from filename
function createGuideId(filename) {
    return filename
        .replace(/\.pdf$/i, '')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
}

// Helper function to create a title from filename
function createTitle(filename) {
    return filename
        .replace(/\.pdf$/i, '')
        .replace(/_/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

// Helper function to generate description
function createDescription(filename) {
    const title = createTitle(filename);
    // Create a more natural description
    return `PDF guide covering ${title.toLowerCase()}`;
}

// Helper function to select an icon based on filename
function selectIcon(filename) {
    const lower = filename.toLowerCase();
    
    // Check more specific patterns first
    if (lower.includes('publish') || lower.includes('decision')) return '📊';
    if (lower.includes('parent') || lower.includes('child') || lower.includes('family')) return '👨‍👩‍👧‍👦';
    if (lower.includes('enrol') || lower.includes('admission') || lower.includes('application')) return '📝';
    if (lower.includes('math') || lower.includes('algebra') || lower.includes('calculus')) return '🔢';
    if (lower.includes('science') || lower.includes('physics') || lower.includes('chemistry')) return '🔬';
    if (lower.includes('code') || lower.includes('program') || lower.includes('computer')) return '💻';
    if (lower.includes('guide') || lower.includes('tutorial')) return '📚';
    
    return '📖'; // Default icon
}

// Main function
function generatePdfManifest() {
    console.log('Scanning pdfs directory...');
    
    try {
        // Check if pdfs directory exists
        if (!fs.existsSync(PDFS_DIR)) {
            console.error('Error: pdfs directory not found');
            process.exit(1);
        }
        
        // Read all files in pdfs directory
        const files = fs.readdirSync(PDFS_DIR);
        
        // Filter for PDF files only
        const pdfFiles = files.filter(file => 
            file.toLowerCase().endsWith('.pdf') && 
            !file.startsWith('.')
        );
        
        console.log(`Found ${pdfFiles.length} PDF files`);
        
        // Generate guide objects for each PDF
        const guides = pdfFiles.map(filename => {
            const guideId = createGuideId(filename);
            const title = createTitle(filename);
            const description = createDescription(filename);
            const icon = selectIcon(filename);
            
            console.log(`  - ${filename} -> ID: ${guideId}`);
            
            return {
                id: guideId,
                title: title,
                description: description,
                file: `pdfs/${filename}`,
                icon: icon,
                autoGenerated: true
            };
        });
        
        // Write manifest file
        const manifest = {
            generatedAt: new Date().toISOString(),
            pdfCount: guides.length,
            guides: guides
        };
        
        fs.writeFileSync(OUTPUT_FILE, JSON.stringify(manifest, null, 2));
        console.log(`\nManifest generated successfully: ${OUTPUT_FILE}`);
        console.log(`Total guides: ${guides.length}`);
        
    } catch (error) {
        console.error('Error generating manifest:', error.message);
        process.exit(1);
    }
}

// Run the script
generatePdfManifest();
